# function to check that a jolly event has the correct structure
# i.e. first element is an integer, second a function
# return boolean
check_event <- function(event){
  # check first element, has to be a time point
  el_1 <- is.double(event[[1]]) && (event[[1]]>0)
  # check second element (needs to be a function)
  el_2 <- is.function(event[[2]])
  return(all(el_1, el_2))
}

