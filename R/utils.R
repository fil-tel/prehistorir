# Set classes (or fix their priorities if already present)
set_class <- function(x, type) {
  other_classes <- class(x)
  c(paste0("prehistorik_", type), other_classes)
}


# extract attributes from prehistorik objects -----------------------------


get_crs <- function(obj){
  if(inherits(obj, "prehistorik_map")) attr(obj, "crs")
  else if(inherits(obj, "prehistorik_model")) get_crs(attr(obj, "map_mat"))
  else stop("The object is not neither of the class prehistorik_map or prehistorik_model." )
}

get_bbox <- function(obj){
  if(inherits(obj, "prehistorik_map")) attr(obj, "bbox")
  else if(inherits(obj, "prehistorik_model")) get_bbox(attr(obj, "map_mat"))
  else stop("The object is not neither of the class prehistorik_map or prehistorik_model." )
}

