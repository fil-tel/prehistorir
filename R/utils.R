get_parameters <- function(obj){
  if(inherits(obj, "prehistorik_model")) attr(obj, "parameters")
}

get_generation_time <- function(obj){
  if(inherits(obj, "prehistorik_model")) {
    parameters <- get_parameters(obj)
    parameters$generation_time
  }else stop("The object is not a prehistorik_model. Are you sure it was generated by the function create_prehistorik_model?")
}

